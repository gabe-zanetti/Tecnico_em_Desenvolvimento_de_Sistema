CREATE DATABASE IF NOT EXISTS BD_ESTOQUE_SUPERMERCADO;
USE BD_ESTOQUE_SUPERMERCADO;

CREATE TABLE IF NOT EXISTS PRODUTOS (
	CODIGO_BARRAS VARCHAR(20) PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    PRECO DOUBLE NOT NULL,
    DESCRICAO VARCHAR(500) NOT NULL,
    VALIDADE DATE,
    QUANTIDADE INT NOT NULL,
    PESO DOUBLE
);

CREATE TABLE IF NOT EXISTS FORNECEDORES (
	CNPJ VARCHAR(14) PRIMARY KEY,
    NOME VARCHAR(50) NOT NULL,
    EMAIL VARCHAR(50) NOT NULL,
    TELEFONE VARCHAR(9) NOT NULL
);

CREATE TABLE IF NOT EXISTS CATEGORIA (
	ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(50) NOT NULL,
    TIPO VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS PRODUTO_FORNECEDOR(
	ID INT AUTO_INCREMENT PRIMARY KEY,
    FK_CODIGO_BARRAS_PRODUTO VARCHAR(20),
    FK_CNPJ_FORNECEDOR VARCHAR(14),
    FOREIGN KEY (FK_CODIGO_BARRAS_PRODUTO) REFERENCES PRODUTOS(CODIGO_BARRAS),
    FOREIGN KEY (FK_CNPJ_FORNECEDOR) REFERENCES FORNECEDORES(CNPJ)
);