CREATE DATABASE IF NOT EXISTS DB_ALUGUEL ;
USE DB_ALUGUEL;

CREATE TABLE IF NOT EXISTS CLIENTE(
	CLIENTE_ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(50),
    CPF VARCHAR(9),
    EMAIL VARCHAR(50),
    TELEFONE INT(20)
);

ALTER TABLE CLIENTE
MODIFY COLUMN CPF VARCHAR (11) NOT NULL UNIQUE;

CREATE TABLE IF NOT EXISTS ALUGUEL(
	ALUGUEL_ID INT AUTO_INCREMENT PRIMARY KEY,
    DATA_ALUGUEL DATE,
    DATA_DEVOLUCAO DATE,
    VALOR_TOTAL DOUBLE NOT NULL,
    FK_CLIENTE_ID INT,
    FOREIGN KEY (FK_CLIENTE_ID) REFERENCES CLIENTE(CLIENTE_ID)

);

CREATE TABLE IF NOT EXISTS PRODUTOS(
	PRODUTO_ID INT AUTO_INCREMENT PRIMARY KEY,
	QTD_PRODUTOS INT,
    PRECO DOUBLE NOT NULL,
    DESCRICAO VARCHAR(200),
    NOME VARCHAR (20)
);

CREATE TABLE IF NOT EXISTS PRODUTO_ALUGUEL(
	PRODUTO_ALUGUEL_ID INT AUTO_INCREMENT PRIMARY KEY,
	FK_PRODUTO_ID INT,
    FOREIGN KEY (FK_PRODUTO_ID) REFERENCES PRODUTOS(PRODUTO_ID),
    FK_ALUGUEL_ID INT,
    FOREIGN KEY (FK_ALUGUEL_ID) REFERENCES ALUGUEL(ALUGUEL_ID)

);

