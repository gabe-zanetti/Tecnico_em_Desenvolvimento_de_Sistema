CREATE DATABASE IF NOT EXISTS BD_APLICATIVO_MUSICA;
USE BD_APLICATIVO_MUSICA;

CREATE TABLE IF NOT EXISTS ARTISTAS(
	CPF_CNPJ VARCHAR(14) PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL,
    TELEFONE VARCHAR(9) NOT NULL
);

CREATE TABLE IF NOT EXISTS ALBUMS(
	ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    DURACAO TIMESTAMP NOT NULL,
    CAPA BLOB NOT NULL,
    FK_CPF_CNPJ_ARTISTA VARCHAR(14),
    FOREIGN KEY (FK_CPF_CNPJ_ARTISTA) REFERENCES ARTISTAS(CPF_CNPJ)
);

CREATE TABLE IF NOT EXISTS GENERO_MUSICAL(
	ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(50) NOT NULL,
    RITMO VARCHAR(100) NOT NULL,
    ESTILO VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS FAIXA(
	ID INT AUTO_INCREMENT PRIMARY KEY,
    OUVINTES INT,
    DURACAO TIMESTAMP NOT NULL,
    LETRA VARCHAR(1000),
    NOME VARCHAR(100) NOT NULL,
    FK_ID_GENERO_MUSICAL INT,
    FK_ID_ALBUM INT,
    FOREIGN KEY (FK_ID_GENERO_MUSICAL) REFERENCES GENERO_MUSICAL(ID),
    FOREIGN KEY (FK_ID_ALBUM) REFERENCES ALBUMS(ID)
);
